#!/usr/bin/env python3
"""Generate a bitmap-text .frag shader from a TTF rasterization.

Usage: gen-banner-frag.py <font.ttf> <text> <out.frag> <scale> <rr,gg,bb> <orr,ogg,obb> [pointsize] [gap]

Produces a shader that renders <text> centered, with a 1px outline in the
outline color, on a transparent background (alpha channel set for
compositing). Characters are rasterized at <pointsize> (default 20) and
bottom-padded to an 8-row cell; glyph advance includes a <gap>-px gap
(default 3 — must be >= 3 so 1px outlines between letters don't merge into
a slab). Rows are emitted top-down and flipped at lookup time (see
resources/shaders/SHADER-NOTES.md).
"""
import importlib.util
import sys
from pathlib import Path

H = None  # recomputed per run from the tallest glyph

def load_rasterizer():
    here = Path(__file__).parent
    spec = importlib.util.spec_from_file_location("f2g", here / "font-to-glsl.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod

def main():
    global H
    font, text, out_path, scale, fill, outline = sys.argv[1:7]
    pointsize = int(sys.argv[7]) if len(sys.argv) > 7 else 20
    gap = int(sys.argv[8]) if len(sys.argv) > 8 else 3
    f2g = load_rasterizer()
    chars = list(text)
    widths, rows_per_char = [], []
    for ch in chars:
        if ch == " ":
            widths.append(3)
            rows_per_char.append([])  # blank; padded after H is known
            continue
        rows = f2g.rasterize(font, ch, pointsize)
        w = max(len(r) for r in rows)
        rows_per_char.append([f2g.row_bits(r) for r in rows])
        widths.append(w)
    # Cell height adapts to the tallest glyph; everything is bottom-padded to it.
    H = max(len(r) for r in rows_per_char)
    rows_per_char = [r + [0] * (H - len(r)) for r in rows_per_char]

    codes = [ord(c) for c in chars]
    n = len(chars)
    flat = [v for rows in rows_per_char for v in rows]

    def fmt(vals, per=14):
        return ", ".join(str(v) for v in vals)

    glsl = f"""#version 300 es
precision highp float;
uniform vec2 u_resolution;
uniform float u_time;
uniform float u_seed;
out vec4 outColor;

// Auto-generated by scripts/gen-banner-frag.py — bitmap text, transparent bg.
// Text: {text!r}
// Infill rgb({fill}) — 1px outline rgb({outline}).
// Rows are TOP-DOWN; the shader flips the row index because gl_FragCoord.y
// grows BOTTOM-UP — see resources/shaders/SHADER-NOTES.md.

const int TEXT_LEN = {n};
const int TEXT[TEXT_LEN] = int[TEXT_LEN]({fmt(codes)});
const int GW[TEXT_LEN] = int[TEXT_LEN]({fmt(widths)});
const int GDATA[TEXT_LEN * {H}] = int[TEXT_LEN * {H}](
  {fmt(flat)}
);

const float S = {scale}.0;                 // glyph pixel scale
const vec3 FILL = vec3({fill}) / 255.0;
const vec3 OUTLINE = vec3({outline}) / 255.0;

bool textOn(vec2 gp) {{
  float x = 0.0;
  for (int i = 0; i < TEXT_LEN; i++) {{
    int w = GW[i];
    if (gp.x >= x && gp.x < x + float(w) && gp.y >= 0.0 && gp.y < {H}.0) {{
      ivec2 c = ivec2(floor(gp) - vec2(x, 0.0));
      int row = {H - 1} - c.y;           // flip: bottom-up fragcoord
      return ((GDATA[{H} * i + row] >> (w - 1 - c.x)) & 1) == 1;
    }}
    x += float(w) + 1.0;
  }}
  return false;
}}

void main() {{
  float totalW = 0.0;
  for (int i = 0; i < TEXT_LEN; i++) totalW += float(GW[i]);
  totalW += float(TEXT_LEN - 1);
  vec2 size = vec2(totalW, {H}.0) * S;
  vec2 origin = (u_resolution - size) * 0.5;

  vec2 gp = (gl_FragCoord.xy - origin) / S;
  bool on = textOn(gp);
  bool edge = false;
  if (!on) {{
    for (int dy = -1; dy <= 1; dy++) {{
      for (int dx = -1; dx <= 1; dx++) {{
        if (dx == 0 && dy == 0) continue;
        edge = edge || textOn(gp + vec2(float(dx), float(dy)));
      }}
    }}
  }}

  vec3 col = on ? FILL : OUTLINE;
  float a = (on || edge) ? 1.0 : 0.0;
  outColor = vec4(col, a);
}}
"""
    Path(out_path).write_text(glsl)
    print(f"wrote {out_path}: text={text!r} {n} glyphs, scale={scale}, "
          f"bitmap={sum(widths)+n-1}x{H}")

if __name__ == "__main__":
    main()
